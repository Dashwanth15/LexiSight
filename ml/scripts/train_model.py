# ?????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????

def _rotate_xyz(pts, angles_deg):
    """Apply XYZ Euler rotation. Falls back to manual if scipy missing."""
    if SCIPY_OK:
        rot = Rotation.from_euler('xyz', angles_deg, degrees=True)
        return rot.apply(pts)
    # numpy fallback: apply Z rotation only
    a = np.radians(angles_deg[2])
    c, s = np.cos(a), np.sin(a)
    R = np.array([[c, -s, 0], [s, c, 0], [0, 0, 1]])
    return pts @ R.T


def generate_synthetic_gesture(base_63, n_samples=150, extra_rotation=False):
    base = np.array(base_63, dtype=np.float32).reshape(21, 3)
    results = []
    rot_range = 35 if extra_rotation else 25

    for _ in range(n_samples):
        v = base.copy()

        # 1. Global rotation (all 3 axes)
        angles = np.random.uniform(-rot_range, rot_range, 3)
        v = _rotate_xyz(v, angles)

        # 2. Scale variation (hand size ??15%)
        scale = np.random.uniform(0.85, 1.15)
        v *= scale

        # 3. MediaPipe jitter noise
        noise_lvl = 0.012 * scale
        v += np.random.normal(0, noise_lvl, v.shape)

        # 4. Z-depth variation
        v[:, 2] += np.random.uniform(-0.08, 0.08)

        # 5. Wrist angle variation
        wrist_ang = np.random.uniform(-10, 10)
        v = _rotate_xyz(v, [0, 0, wrist_ang])

        # 6. Per-finger micro tremor
        for joints in FINGER_JOINTS.values():
            v[joints] += np.random.normal(0, 0.008, (len(joints), 3))

        # 7. Perspective distortion
        pf = np.random.uniform(0.97, 1.03)
        v[:, 0] *= pf
        v[:, 1] /= pf

        # Re-normalise (wrist to origin, scale by middle-MCP distance)
        v -= v[0]
        s = np.linalg.norm(v[9])
        if s > 1e-6:
            v /= s

        results.append(v.flatten())

    return np.array(results, dtype=np.float32)


def generate_full_synthetic(X_real, y_real, spc=150, extra_rotation=False):
    """Generate synthetic samples for every class from median real sample."""
    classes = np.unique(y_real)
    X_syn, y_syn = [], []
    for cls in classes:
        mask = y_real == cls
        samples = X_real[mask]
        if len(samples) == 0:
            continue
        base = np.median(samples, axis=0)
        syn  = generate_synthetic_gesture(base, n_samples=spc,
                                          extra_rotation=extra_rotation)
        X_syn.append(syn)
        y_syn.extend([cls] * len(syn))
        print(f"  ??? Class {cls}: +{len(syn)} synthetic", flush=True)
    return np.vstack(X_syn), np.array(y_syn)


def enforce_ratio(X_tr, y_tr, X_syn, y_syn, ratio=0.30):
    """Keep synthetic ??? 30% of total training set."""
    n_real   = len(X_tr)
    max_syn  = int(n_real * ratio / (1.0 - ratio))
    if len(X_syn) > max_syn:
        idx   = np.random.choice(len(X_syn), max_syn, replace=False)
        X_syn = X_syn[idx]
        y_syn = y_syn[idx]
        print(f"  Downsampled synthetic ??? {len(X_syn):,}", flush=True)
    actual = len(X_syn) / (n_real + len(X_syn))
    print(f"  Ratio ??? Real: {1-actual:.0%}  Synthetic: {actual:.0%}", flush=True)
    X_comb = np.vstack([X_tr, X_syn])
    y_comb = np.hstack([y_tr, y_syn])
    idx    = np.random.permutation(len(X_comb))
    return X_comb[idx], y_comb[idx]


