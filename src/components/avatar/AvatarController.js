// DESIGN PHILOSOPHY:
//   This module governs the interpolation math and transition blending.
//   It ensures that transitions between different words, letters, digits,
//   and the idle breathing state remain fluid and weighty, avoiding high-speed snaps.

import * as THREE from 'three'

/**
 * Smoothly interpolates the current pose state towards the target pose state.
 * Uses spring-like exponential lerping for frame-rate independence.
 *
 * @param {Object} curr - Current pose object (modified in-place)
 * @param {Object} target - Target pose object
 * @param {number} lf - Lerp factor for fingers/wrists (~fast)
 * @param {number} armLf - Lerp factor for arms/shoulders (~medium-slow)
 * @param {number} posLf - Lerp factor for root group positioning (~slow, weighted)
 */
export function interpolatePose(curr, target, lf, armLf, posLf) {
  if (!curr || !target) return

  // 1. Interpolate finger joints [MCP, PIP, DIP]
  const fingers = ['thumb', 'index', 'middle', 'ring', 'pinky']
  for (const finger of fingers) {
    const currJoints = curr[finger]
    const tgtJoints = target[finger] ?? [0, 0, 0]
    
    for (let i = 0; i < 3; i++) {
      const tgtVal = tgtJoints[i] ?? 0
      currJoints[i] = THREE.MathUtils.lerp(currJoints[i], tgtVal, lf)
    }
  }

  // 2. Interpolate wrist rotation (palmRotate)
  curr.palmRotate = THREE.MathUtils.lerp(curr.palmRotate, target.palmRotate ?? 0, lf)

  // 3. Interpolate forearm rotations (lift, roll)
  if (!curr.arm) curr.arm = { lift: 0, roll: 0 }
  const ta = target.arm ?? { lift: 0, roll: 0 }
  curr.arm.lift = THREE.MathUtils.lerp(curr.arm.lift, ta.lift ?? 0, armLf)
  curr.arm.roll = THREE.MathUtils.lerp(curr.arm.roll, ta.roll ?? 0, armLf)

  // 4. Interpolate root group positions (x, y, z)
  if (!curr.pos) curr.pos = { x: 0, y: 0, z: 0 }
  const tp = target.pos ?? { x: 0, y: 0, z: 0 }
  curr.pos.x = THREE.MathUtils.lerp(curr.pos.x, tp.x ?? 0, posLf)
  curr.pos.y = THREE.MathUtils.lerp(curr.pos.y, tp.y ?? 0, posLf)
  curr.pos.z = THREE.MathUtils.lerp(curr.pos.z, tp.z ?? 0, posLf)

  // 5. Interpolate body rotations (x, y)
  curr.bodyRotateX = THREE.MathUtils.lerp(curr.bodyRotateX ?? 0, target.bodyRotateX ?? 0, posLf)
  curr.bodyRotateY = THREE.MathUtils.lerp(curr.bodyRotateY ?? 0, target.bodyRotateY ?? 0, posLf)
}

/**
 * Integrates dynamic idle breathing and micro-movements into the target pose.
 * 
 * @param {Object} pose - Current procedural pose (modified in-place)
 * @param {Object} idleState - Dynamic breathing sways generated by AnimationManager
 */
export function blendPoseWithIdle(pose, idleState) {
  if (!pose || !idleState) return

  // Apply subtle micro-vibrations to arm rotations for a organic flesh-and-blood feel
  if (pose.arm) {
    pose.arm.lift += idleState.arms.idleX * RAD_TO_DEG
    pose.arm.roll += idleState.arms.idleZ * RAD_TO_DEG
  }

  // Apply subtle chest breathing to joint offsets
  if (pose.pos) {
    pose.pos.y += idleState.body.breathY
  }
}

const RAD_TO_DEG = 180 / Math.PI
