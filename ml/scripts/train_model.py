def run_two_phase(model, X_combined, y_combined_oh,
                  X_tr_real, y_tr_real_oh,
                  X_val, y_val_oh, cw):
    """Phase 1: hybrid.  Phase 2: real-only fine-tune."""

    p1_cb = [
        EarlyStopping(patience=20, restore_best_weights=True, monitor="val_accuracy"),
        ReduceLROnPlateau(patience=8, factor=0.5, min_lr=1e-6, monitor="val_accuracy"),
        ModelCheckpoint(str(LOGS_DIR/"phase1_best.keras"),
                        save_best_only=True, monitor="val_accuracy"),
    ]
    print("\n???? Phase 1 ??? Hybrid (real+synthetic)...", flush=True)
    h1 = model.fit(X_combined, y_combined_oh,
                   validation_data=(X_val, y_val_oh),
                   epochs=150, batch_size=64,
                   callbacks=p1_cb, class_weight=cw, verbose=1)
    p1_acc = max(h1.history["val_accuracy"])
    print(f"   Phase 1 best: {p1_acc:.2%}", flush=True)

    model.optimizer.learning_rate = 1e-4
    p2_cb = [
        EarlyStopping(patience=15, restore_best_weights=True, monitor="val_accuracy"),
        ModelCheckpoint(str(LOGS_DIR/"phase2_best.keras"),
                        save_best_only=True, monitor="val_accuracy"),
    ]
    print("\n???? Phase 2 ??? Fine-tune (real only)...", flush=True)
    h2 = model.fit(X_tr_real, y_tr_real_oh,
                   validation_data=(X_val, y_val_oh),
                   epochs=100, batch_size=32,
                   callbacks=p2_cb, class_weight=cw, verbose=1)
    p2_acc = max(h2.history["val_accuracy"])
    print(f"   Phase 2 best: {p2_acc:.2%}  (?? {(p2_acc-p1_acc)*100:+.1f}%)", flush=True)
    return model, p1_acc, p2_acc, h1, h2


def train_single(seed, X_combined, y_comb_oh,
                 X_tr_real, y_tr_oh, X_val, y_val_oh, cw,
                 n_classes, extra_block=False):
    tf.random.set_seed(seed)
    np.random.seed(seed)
    m = build_model(n_classes, extra_block)
    m, p1, p2, h1, h2 = run_two_phase(
        m, X_combined, y_comb_oh,
        X_tr_real, y_tr_oh,
        X_val, y_val_oh, cw,
    )
    return m, p2, h1, h2


