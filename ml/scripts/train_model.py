def build_model(n_classes, extra_block=False):
    reg = tf.keras.regularizers.l2(5e-5)
    inp = layers.Input(shape=(63,), name="landmarks_input")

    x = layers.GaussianNoise(0.01)(inp)

    # Block 1
    x = layers.Dense(512, kernel_regularizer=reg)(x)
    x = layers.BatchNormalization(momentum=0.9)(x)
    x = layers.Activation("relu")(x)
    x = layers.Dropout(0.40)(x)

    # Block 2 + residual
    residual = layers.Dense(256)(x)
    x = layers.Dense(256, kernel_regularizer=reg)(x)
    x = layers.BatchNormalization(momentum=0.9)(x)
    x = layers.Activation("relu")(x)
    x = layers.Dropout(0.35)(x)
    x = layers.Add()([x, residual])

    # Optional extra block (Fix D)
    if extra_block:
        x = layers.Dense(256, kernel_regularizer=reg)(x)
        x = layers.BatchNormalization(momentum=0.9)(x)
        x = layers.Activation("relu")(x)
        x = layers.Dropout(0.45)(x)

    # Block 3
    x = layers.Dense(128, kernel_regularizer=reg)(x)
    x = layers.BatchNormalization(momentum=0.9)(x)
    x = layers.Activation("relu")(x)
    x = layers.Dropout(0.25)(x)

    # Block 4
    x = layers.Dense(64, kernel_regularizer=reg)(x)
    x = layers.BatchNormalization(momentum=0.9)(x)
    x = layers.Activation("relu")(x)
    x = layers.Dropout(0.10)(x)

    out = layers.Dense(n_classes, activation="softmax", name="gesture_output")(x)
    model = tf.keras.Model(inputs=inp, outputs=out)

    loss = tf.keras.losses.CategoricalCrossentropy(label_smoothing=0.1)
    model.compile(
        optimizer=tf.keras.optimizers.Adam(1e-3),
        loss=loss,
        metrics=["accuracy",
                 tf.keras.metrics.TopKCategoricalAccuracy(k=3, name="top3_acc")],
    )
    return model


